console.log('Reference URLs:',Object.keys(references).length);
console.log('Lesson-specific resource sets:',Object.keys(learningAssets).length);
console.log('Validation:',problems.length?'FAIL':'PASS');
for(const p of problems)console.log(' -',p);
process.exitCode=problems.length?1:0;
