import {statSync, existsSync, readFileSync} from 'node:fs';
import {join,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';
import {chapters,tracks,references} from '../src/data/course.ts';
import {installs} from '../src/data/install.ts';
import {learningAssets} from '../src/data/learningAssets.ts';
const root=dirname(dirname(fileURLToPath(import.meta.url)));
const problems=[];
const requirePath=(path)=>{if(!existsSync(join(root,path))) problems.push('missing '+path);};
for(let i=0;i<tracks.length;i++){
 const p=`public/audio/${tracks[i].file}`;
 requirePath(p);
 if(existsSync(join(root,p))&&statSync(join(root,p)).size<100_000)problems.push('suspicious audio size '+p);
}
let previousTrack=0,previousTime=-1;
for(const ch of chapters){
 if(!learningAssets[ch.id])problems.push('missing lesson-specific resource '+ch.id);
 else if(!learningAssets[ch.id].explore||!learningAssets[ch.id].recover||!learningAssets[ch.id].reference)problems.push('incomplete contextual resource '+ch.id);
 if(!(ch.track>=0&&ch.track<tracks.length))problems.push('bad track '+ch.id);
 else if(ch.at<0 || ch.at>=tracks[ch.track].length) problems.push('bad time '+ch.id);
 if(ch.track<previousTrack||(ch.track===previousTrack&&ch.at<previousTime))problems.push('out-of-order chapter '+ch.id);
 previousTrack=ch.track;previousTime=ch.at;
 for(const r of ch.resources) if(!references[r])problems.push('unknown resource '+r);
 if(ch.resourceCue && (!ch.resources.includes(ch.resourceCue.key)||ch.resourceCue.at<ch.at||ch.resourceCue.at>=tracks[ch.track].length))problems.push('bad resourceCue '+ch.id);
 for(const cue of ch.cues||[]) if(!(cue.to<=tracks[ch.track].length+.01&&cue.from>=0&&cue.from<cue.to))problems.push('bad cue '+ch.id);
}
requirePath('public/downloads/module-1-labs.zip');
requirePath('public/.nojekyll');
requirePath('public/video/iso-mod2-animation.mp4');
requirePath('public/video/iso-mod2-poster.jpg');
requirePath('src/pages/resources/shared-state.astro');
requirePath('.github/workflows/deploy-pages.yml');
requirePath('src/pages/index.astro');
if(installs.length!==4)problems.push('expected four OS install paths');
if(!readFileSync(join(root,'src/components/MachineReadiness.astro'),'utf8').includes('readinessChecks.map'))problems.push('missing pre-course machine readiness checklist');
if(readFileSync(join(root,'src/pages/index.astro'),'utf8').includes('readinessChecks.map'))problems.push('readiness should not remain in 00.0');
if(!readFileSync(join(root,'src/pages/index.astro'),'utf8').includes('Course Prerequisites'))problems.push('pre-course nav link missing');
requirePath('src/pages/prerequisites.astro');
requirePath('preview-prerequisites.html');
requirePath('public/audio/course-prerequisites.mp3');
if(!readFileSync(join(root,'src/pages/prerequisites.astro'),'utf8').includes('id="prerequisite-assessment"')) problems.push('missing prerequisite completion self-check');
if(!readFileSync(join(root,'src/pages/prerequisites.astro'),'utf8').includes('course-prerequisites.mp3')) problems.push('missing prerequisite narration player');
requirePath('COURSE-PREREQUISITES-NARRATION.md');
if(!readFileSync(join(root,'src/data/readiness.ts'),'utf8').includes('RHEL / Fedora'))problems.push('missing RHEL / Fedora readiness command path');
if(!installs.some(p=>p.label==='RHEL / Fedora'))problems.push('missing combined RHEL / Fedora installation path');
const mediaResource=references['shared-state-animation'];
const stateChapter=chapters.find(c=>c.id==='m2-shared-state');
if(!mediaResource||mediaResource.url!=='resources/shared-state/'||!stateChapter||stateChapter.resourceCue?.at!==177)problems.push('shared-state contextual resource missing or mis-timed');
const css=readFileSync(join(root,'src/styles/site.css'),'utf8');
const experience=readFileSync(join(root,'src/scripts/experience.ts'),'utf8');
if(experience.includes("'Ⅱ'")||experience.includes('playSymbol.textContent'))problems.push('Roman-numeral pause glyph remains');
if(!experience.includes("feature.hidden=!showVideo"))problems.push('animation must be directly available in relevant lessons');
if(!readFileSync(join(root,'src/pages/index.astro'),'utf8').includes('<video controls playsinline'))problems.push('missing inline module 2 video');
if(Object.keys(learningAssets).length!==chapters.length)problems.push('wrong number of pedagogical resource sets');
if(chapters.some(c=>c.lesson==='00.6'||c.id==='next'))problems.push('00.6 must be merged into 00.5');
if(chapters.filter(c=>c.lesson==='00.5').length!==1||chapters.find(c=>c.id==='checkpoint')?.cues?.every(c=>c.from<163))problems.push('missing merged checkpoint to handoff narration');
if(!readFileSync(join(root,'src/pages/index.astro'),'utf8').includes('checkpoint-handoff'))problems.push('merged checkpoint missing in Astro lesson');
if(!experience.includes('alignChapterCard(section)')) problems.push('missing chapter viewport alignment');
if(!experience.includes('renderResources(chosen,t)')) problems.push('missing in-track resource cue synchronization');
if(!experience.includes('cip-course-prerequisites-visited-from-welcome') || !experience.includes('[data-prereq-entry]') || !experience.includes('if(!narrationUnlocked)'))problems.push('main narration prerequisite click gate missing');
if(!readFileSync(join(root,'src/pages/index.astro'),'utf8').includes('data-prereq-entry'))problems.push('welcome card prerequisite action missing');
if(!experience.includes('keepCurrentChapterVisible(id)')) problems.push('missing active chapter sidebar visibility');
if(/\.lesson-beat\s*\{\s*scroll-margin-top/.test(css)) problems.push('chapter margin must not add a second scroll offset');
if(css.includes('opacity:0}.lesson-beat')||css.includes('.lesson-beat{opacity:0'))problems.push('lesson visibility hidden by CSS');
if(tracks.length!==10||chapters.filter(c=>c.module===3).length!==9) problems.push('Module 3 must include three recordings and nine integrated chapters');
for(const chapter of chapters.filter(c=>c.module===3)) if(!chapter.resources.some(key=>references[key]?.label==='WATCH · YOUTUBE')) problems.push('missing Module 3 video resource '+chapter.id);
